-- 알고리즘 설계 슬라이드 기반 스키마
-- Supabase SQL Editor에서 전체 실행

-- ===== 영양소 마스터 =====
create table if not exists public.nutrients (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  purpose text not null default '',
  help_summary text not null default '',
  precautions text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

-- ===== 증상 카테고리 / 세부 증상 =====
create table if not exists public.symptom_categories (
  id bigint generated by default as identity primary key,
  code text not null unique,
  title text not null,
  emoji text not null default '',
  sort_order integer not null default 0
);

create table if not exists public.symptoms (
  id bigint generated by default as identity primary key,
  code text not null unique,
  category_id bigint not null references public.symptom_categories (id) on delete cascade,
  label text not null,
  sort_order integer not null default 0
);

create table if not exists public.symptom_nutrients (
  symptom_id bigint not null references public.symptoms (id) on delete cascade,
  nutrient_id bigint not null references public.nutrients (id) on delete cascade,
  sort_order integer not null default 0,
  primary key (symptom_id, nutrient_id)
);

-- ===== 자판기 상품 =====
create table if not exists public.vitamins (
  id bigint generated by default as identity primary key,
  nutrient_id bigint not null references public.nutrients (id),
  name text not null,
  category text not null,
  price integer not null check (price > 0),
  serving_content text not null default '',
  form text not null default '',
  remarks text not null default '',
  image_url text,
  description text not null default '',
  stock integer not null default 100 check (stock >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists vitamins_nutrient_idx on public.vitamins (nutrient_id);
create index if not exists vitamins_category_idx on public.vitamins (category);
create index if not exists vitamins_active_idx on public.vitamins (is_active);
create index if not exists symptoms_category_idx on public.symptoms (category_id);

comment on table public.vitamins is '자판기 판매 제품 (슬라이드 제품표 24종)';
comment on column public.vitamins.price is '1회분 파우치당 가격(원)';
comment on column public.vitamins.category is '영양소 표시명 (nutrients.name 과 동일)';

-- ===== RLS =====
alter table public.nutrients enable row level security;
alter table public.symptom_categories enable row level security;
alter table public.symptoms enable row level security;
alter table public.symptom_nutrients enable row level security;
alter table public.vitamins enable row level security;

drop policy if exists "nutrients_public_read" on public.nutrients;
create policy "nutrients_public_read" on public.nutrients for select to anon, authenticated using (true);

drop policy if exists "symptom_categories_public_read" on public.symptom_categories;
create policy "symptom_categories_public_read" on public.symptom_categories for select to anon, authenticated using (true);

drop policy if exists "symptoms_public_read" on public.symptoms;
create policy "symptoms_public_read" on public.symptoms for select to anon, authenticated using (true);

drop policy if exists "symptom_nutrients_public_read" on public.symptom_nutrients;
create policy "symptom_nutrients_public_read" on public.symptom_nutrients for select to anon, authenticated using (true);

drop policy if exists "vitamins_public_read" on public.vitamins;
create policy "vitamins_public_read" on public.vitamins for select to anon, authenticated using (is_active = true);

-- ===== updated_at =====
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists vitamins_set_updated_at on public.vitamins;
create trigger vitamins_set_updated_at
  before update on public.vitamins
  for each row execute function public.set_updated_at();
